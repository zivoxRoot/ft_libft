#include <unistd.h>

#include "libft.h"

void	ft_putnbr_fd(int n, int fd)
{
	if (n == 0)
	{
		ft_putchar_fd('0', fd);
		return;
	}
	ft_putstr_fd(ft_itoa(n), fd);
}
